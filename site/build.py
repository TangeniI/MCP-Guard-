"""Builds site/data.js from the results files, so every number on the
showcase page comes from evals/results/ and none is typed by hand.

    python3 site/build.py
"""

import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "evals" / "results"

MODES = [("off", "Gateway off"), ("policy", "Policy only"), ("content", "Scanning + pinning only"), ("both", "Both layers")]
CATEGORIES = [
    ("path_escape", "Files outside the allowed folder"),
    ("unauthorised_tool", "Tools never granted to the agent"),
    ("tool_changed_after_approval", "Tool changed after first sight"),
    ("argument_exfiltration", "Data leaked through tool arguments"),
    ("poisoned_tool_description", "Poisoned tool descriptions"),
    ("result_injection", "Prompt injection in tool results"),
]


def pair(t):
    return [t["pass"], t["total"]]


def scenarios():
    path = sorted(RESULTS.glob("scenarios-*.json"))[-1]
    r = json.loads(path.read_text())
    s = r["summary"]
    return {
        "file": path.name,
        "date": r["date_utc"][:10],
        "total": r["scenarios"],
        "modes": [
            {"key": k, "label": label,
             **{split: {"attacks": pair(s[k][split]["attacks blocked"]), "benign": pair(s[k][split]["benign working"])}
                for split in ("all", "heldout")}}
            for k, label in MODES
        ],
        "categories": [
            {"key": k, "label": label, "all": pair(s["both"]["all"][k]), "heldout": pair(s["both"]["heldout"][k])}
            for k, label in CATEGORIES
        ],
        "misses": r["misses_with_both_layers"],
    }


def agentdojo():
    def load(pattern):
        path = sorted(RESULTS.glob(pattern))[-1]
        return path.name, json.loads(path.read_text())

    name, r = load("agentdojo-*-ground-truth-guard-scan.json")
    b, a = r["totals"]["benign"], r["totals"]["under_attack"]
    medians = [s["latency"]["added_ms_median"] for s in r["suites"].values()]
    out = {
        "scripted": {
            "file": name, "date": r["date_utc"][:10], "tasks": b["tasks"], "pairs": a["pairs"],
            "injected": a["injected_results"], "injected_quarantined": a["injected_results_quarantined"],
            "benign_results": b["tool_calls"], "benign_quarantined": b["quarantined_calls"],
            "added_ms_median": round(statistics.median(medians), 3),
            "attack": r["attack"]["name"],
        }
    }
    pilot = {}
    for guard in ("off", "scan"):
        name, r = load(f"agentdojo-*-guard-{guard}-pilot.json")
        b, a = r["totals"]["benign"], r["totals"]["under_attack"]
        pilot[guard] = {
            "file": name, "benign": [b["utility"], b["tasks"]], "utility_under_attack": [a["utility"], a["pairs"]],
            "attacks_succeeded": [a["attack_successes"], a["pairs"]],
            "injected_quarantined": [a["injected_results_quarantined"], a["injected_results"]],
        }
        pilot["model"], pilot["date"], pilot["suite"] = r["agent"]["model"], r["date_utc"][:10], ", ".join(r["suites"])
    out["pilot"] = pilot
    return out


data = {"scenarios": scenarios(), "agentdojo": agentdojo()}
out = Path(__file__).resolve().parent / "data.js"
out.write_text("// Generated by site/build.py from evals/results/. Do not edit.\nwindow.MCPGUARD = "
               + json.dumps(data, indent=1) + ";\n")
print("wrote", out.relative_to(ROOT), "from", data["scenarios"]["file"])
